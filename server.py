#!/usr/bin/env python3
"""HTTP API for the trending-audio downloader — drop-in for content automation.

Endpoints
---------
POST /v1/download        {"url": "...", "niche": "...", "title": "...", "artist": "..."}
                          -> downloads the audio, saves to library/<niche>/, returns
                             {ok, path, title, artist, provider, sha256, bytes,
                              duration_s, cached, storage, ...}
                          ?cookies=... (JSON browser export OR a Netscape cookie
                          string) supplies a session for Instagram/private sources
POST /v1/song            {"title": "...", "artist": "...", "niche": "reels",
                          "instagram_url": "...", "cookies": [...]}
                          -> resolves a song NAME to audio: Instagram (URL, then
                             audio-page search) first, then SoundCloud/YouTube.
                             Use this with a row from /v1/trending to get the
                             actual trending track.
GET  /v1/library/<niche>  -> list of saved entries (manifest)
GET  /v1/file/<niche>/<name>  -> serve the downloaded audio file
GET  /health              -> liveness + library storage accounting

Run
---
.venv/bin/python server.py --port 8000 --library /path/library
Then POST from your automation system, e.g.:
  curl -X POST localhost:8000/v1/download \
       -H 'Content-Type: application/json' \
       -d '{"url":"https://www.instagram.com/reel/XXXX/","niche":"self-improvement"}'
"""
from __future__ import annotations

import argparse
import json
import os
import tempfile

from flask import Flask, jsonify, request, send_file, abort

from trend_scraper.audio import AudioLibrary

ROOT = os.path.dirname(os.path.abspath(__file__))
DEFAULT_LIBRARY = os.getenv("TL_LIBRARY", os.path.join(ROOT, "library"))
_MAX_CONCURRENT = int(os.getenv("TL_MAX_CONCURRENT", "2"))  # yt-dlp+ffmpeg is RAM-heavy

app = Flask(__name__)
app.config["MAX_CONTENT_LENGTH"] = 2 * 1024 * 1024  # request body cap (2MB, urls only)
app.config["LIBRARY"] = DEFAULT_LIBRARY             # set at import; gunicorn loads app directly

# Serialize heavy downloads so a burst of requests can't OOM a free-tier instance.
_download_slots = __import__("threading").BoundedSemaphore(max(1, _MAX_CONCURRENT))


def _write_cookies(cookies) -> str | None:
    """Persist session cookies to a Netscape cookie file for yt-dlp.

    Accepts either:
      * a Netscape-format string (used verbatim), or
      * a list/dict of cookie objects (browser-export shape:
        [{name, value, domain, path, secure, expirationDate}, ...]).

    yt-dlp's `cookiefile` ONLY understands Netscape format. Writing the JSON dict
    straight to disk (the previous behaviour) made every authenticated fetch fail
    to parse, which is why Instagram downloads could never succeed.
    """
    if not cookies:
        return None
    fd, path = tempfile.mkstemp(suffix=".txt")
    with os.fdopen(fd, "w") as fh:
        if isinstance(cookies, str):
            text = cookies.strip()
            if text.startswith("# Netscape") or "\t" in text:
                fh.write(text if text.endswith("\n") else text + "\n")
                return path
            try:                       # tolerate a JSON string body
                cookies = json.loads(text)
            except Exception:          # noqa: BLE001
                fh.write(text if text.endswith("\n") else text + "\n")
                return path

        # normalise to a list of cookie dicts
        if isinstance(cookies, dict):
            items = []
            for name, value in cookies.items():
                if isinstance(value, dict):
                    items.append({"name": name, **value})
                else:
                    items.append({"name": name, "value": value})
            cookies = items

        fh.write("# Netscape HTTP Cookie File\n")
        fh.write("# generated by trending-audio-api\n")
        for c in cookies or []:
            if not isinstance(c, dict):
                continue
            name = str(c.get("name") or "").strip()
            if not name:
                continue
            value = str(c.get("value") or "")
            domain = str(c.get("domain") or ".instagram.com").strip()
            cpath = str(c.get("path") or "/")
            secure = "TRUE" if c.get("secure") else "FALSE"
            expires = c.get("expirationDate") or c.get("expires") or 0
            try:
                expires = int(float(expires))
            except (TypeError, ValueError):
                expires = 0
            # domain-scope flag: TRUE when the cookie applies to subdomains
            scope = "TRUE" if domain.startswith(".") else "FALSE"
            fh.write("\t".join([domain, scope, cpath, secure,
                                str(expires), name, value]) + "\n")
    return path


