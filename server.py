@app.get("/v1/trending/<niche>")
def trending(niche: str):
    """Return ranked trending audio for a niche (discovery, cached per day).

    Runs the browser-free discovery path so it is safe on the free-tier API:
    aggregator/evergreen feeds + Wayback, no headless browser. Results are
    ranked by the composite trend score (cross-source corroboration + momentum).
    """
    try:
        limit = max(1, min(int(request.args.get("limit", 20)), 100))
    except ValueError:
        limit = 20
    use_cache = request.args.get("refresh", "0") != "1"
    try:
        from trend_scraper import Niche, TrendingAudioEngine
        engine = TrendingAudioEngine(
            cache_dir=os.path.join(app.config["LIBRARY"], "_trending"),
            use_search=True,         # browser-free Bing/DDG-HTML search
            use_stealth=False,       # no chromium on the free-tier image
            deadline_s=float(os.getenv("TL_TRENDING_BUDGET_S", "90")),
        )
        tracks = engine.collect(Niche.from_name(niche), use_cache=use_cache)
        return jsonify({
            "niche": Niche.from_name(niche).name,
            "count": min(limit, len(tracks)),
            "cached": use_cache,
            "results": [t.__dict__ for t in tracks[:limit]],
        })
    except Exception as exc:
        return jsonify({"ok": False, "message": str(exc)[:300]}), 500


@app.get("/v1/niches")
def niches():
    """List the niches the engine understands."""
    from trend_scraper.niches import all_niches
    return jsonify({"niches": all_niches()})


@app.get("/health")
def health():
    """Liveness + storage accounting.

    Reports the library footprint against its cap so the automation side can see
    storage pressure before a download fails on it.
    """
    lib = AudioLibrary(app.config["LIBRARY"],
                       provider="url",
                       max_bytes=int(os.getenv("TL_MAX_LIBRARY_MB", "700")) * 1024 * 1024)
    try:
        st = lib.stats()
    except Exception as exc:  # noqa: BLE001
        st = {"error": str(exc)[:200]}
    return jsonify({"status": "ok", "library": app.config["LIBRARY"], "storage": st})


def _disk_free_bytes(path: str) -> int:
    try:
        st = os.statvfs(path)
        return st.f_frsize * st.f_bavail
    except Exception:  # noqa: BLE001
        return -1


@app.post("/v1/download")
def download():
    data = request.get_json(silent=True) or {}
    url = (data.get("url") or "").strip()
    if not url.startswith(("http://", "https://")):
        return jsonify({"ok": False, "message": "a valid http(s) url is required"}), 400

    niche = (data.get("niche") or "manual").strip() or "manual"
    cookies_path = _write_cookies(data.get("cookies"))
    try:
        cap_mb = int(os.getenv("TL_MAX_LIBRARY_MB", "700"))
        lib = AudioLibrary(app.config["LIBRARY"],
                           provider="url",
                           cookies_file=cookies_path,
                           max_bytes=cap_mb * 1024 * 1024)

        # Refuse BEFORE downloading when the disk itself is nearly full. A failed
        # yt-dlp mid-write is what turns "disk full" into a crashed service; the
        # library cap alone cannot prevent it because one track can be large.
        free = _disk_free_bytes(app.config["LIBRARY"])
        min_free = int(float(os.getenv("TL_MIN_FREE_MB", "60")) * 1024 * 1024)
        if free >= 0 and free < min_free:
            try:
                lib._prune()          # try to make room first
            except Exception:         # noqa: BLE001
                pass
            free = _disk_free_bytes(app.config["LIBRARY"])
            if free < min_free:
                return jsonify({
                    "ok": False,
                    "message": (f"insufficient disk: {free // 1048576}MB free, "
                                f"{min_free // 1048576}MB required"),
                    "storage": lib.stats(),
                }), 507

        _download_slots.acquire()
        try:
            entry = lib.download_url(url, niche=niche,
                                     title=(data.get("title") or "").strip() or None,
                                     artist=(data.get("artist") or "").strip() or None)
        finally:
            _download_slots.release()
        entry.setdefault("storage", lib.stats())
        status = 200 if entry.get("ok") else 502
        return jsonify(entry), status
    except Exception as exc:
        return jsonify({"ok": False, "message": str(exc)[:300]}), 500
    finally:
        if cookies_path:
            try:
                os.remove(cookies_path)
            except OSError:
                pass


@app.post("/v1/song")
def song():
    """Resolve a song NAME to audio (Instagram-first, then name search).

    Body: {"title": "...", "artist": "...", "niche": "reels",
           "instagram_url": "https://www.instagram.com/reel/.../",   # optional
           "cookies": [...]}                                          # optional
    This is the endpoint for "use the actual trending ones": feed it a row from
    /v1/trending and it comes back with a real audio file.
    """
    data = request.get_json(silent=True) or {}
    title = (data.get("title") or "").strip()
    if not title:
        return jsonify({"ok": False, "message": "title is required"}), 400

    niche = (data.get("niche") or "reels").strip() or "reels"
    ig_url = (data.get("instagram_url") or data.get("url") or "").strip() or None
    cookies_path = _write_cookies(data.get("cookies"))
    try:
        lib = AudioLibrary(app.config["LIBRARY"], provider="song",
                           cookies_file=cookies_path,
                           max_bytes=int(os.getenv("TL_MAX_LIBRARY_MB", "600")) * 1024 * 1024)
        free = _disk_free_bytes(app.config["LIBRARY"])
        min_free = int(float(os.getenv("TL_MIN_FREE_MB", "80")) * 1024 * 1024)
        if free >= 0 and free < min_free:
            return jsonify({"ok": False,
                            "message": f"insufficient disk: {free // 1048576}MB free",
                            "storage": lib.stats()}), 507

        _download_slots.acquire()
        try:
            entry = lib.download_song(title, (data.get("artist") or "").strip(),
                                      niche=niche, instagram_url=ig_url)
        finally:
            _download_slots.release()
        entry.setdefault("storage", lib.stats())
        return jsonify(entry), (200 if entry.get("ok") else 502)
    except Exception as exc:
        return jsonify({"ok": False, "message": str(exc)[:300]}), 500
    finally:
        if cookies_path:
            try:
                os.remove(cookies_path)
            except OSError:
                pass


@app.get("/v1/library/<niche>")
def library(niche: str):
    manifest = os.path.join(app.config["LIBRARY"],
                            niche.strip().lower().replace(" ", "-"), "manifest.json")
    if not os.path.exists(manifest):
        return jsonify({"niche": niche, "entries": []})
    return jsonify({"niche": niche,
                    "entries": json.load(open(manifest))})


@app.get("/v1/file/<niche>/<path:filename>")
def serve_file(niche: str, filename: str):
    safe = os.path.basename(filename)  # no path traversal
    base = os.path.join(app.config["LIBRARY"], niche.strip().lower().replace(" ", "-"))
    target = os.path.abspath(os.path.join(base, safe))
    if not target.startswith(os.path.abspath(base)) or not os.path.isfile(target):
        abort(404)
    return send_file(target, as_attachment=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=int(os.getenv("PORT", "8000")))
    ap.add_argument("--host", default=os.getenv("HOST", "0.0.0.0"))
    ap.add_argument("--library", default=DEFAULT_LIBRARY)
    args = ap.parse_args()
    os.makedirs(args.library, exist_ok=True)
    app.config["LIBRARY"] = args.library
    app.run(host=args.host, port=args.port, threaded=True,
            debug=os.getenv("FLASK_DEBUG", "0") == "1")


if __name__ == "__main__":
    main()
